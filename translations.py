def t(key: str, lang: str = "en") -> str:
    """Retrieves localized text string."""
    lang_clean = "ta" if lang == "ta" else "en"
    if key in TEXT_STRINGS:
        return TEXT_STRINGS[key].get(lang_clean, TEXT_STRINGS[key]["en"])
    return key


def get_localized_condition_name(condition_raw: str, default_name: str, lang: str = "en") -> str:
    """Translates condition names into Tamil if active."""
    if lang == "ta" and condition_raw in CONDITION_TRANSLATIONS_TA:
        return CONDITION_TRANSLATIONS_TA[condition_raw]
    return default_name


def get_localized_crop_name(crop: str, lang: str = "en") -> str:
    """Translates crop names into Tamil if active."""
    if lang == "ta" and crop in CROP_TRANSLATIONS_TA:
        return CROP_TRANSLATIONS_TA[crop]
    return crop


